# shellcheck shell=bash
# Sourced by scripts/setup.sh and scripts/seed-worktree.sh; run from the repo
# root. Not executable on its own.
#
# ensure_fast_linker — wire mold (lld only when mold is not installed) as the
# Linux host linker by writing the gitignored `.cargo/config.toml`. The link
# step is the long pole of incremental Rust compiles (docs/BUILD.md → "Speed
# up Rust builds"), and the config is gitignored, so a fresh clone and every
# `git worktree add` checkout starts without it.
#
# Best-effort and idempotent: only touches the Linux host triple (Android and
# cross builds are unaffected), skips when neither linker is on PATH, and never
# overwrites an existing `.cargo/config.toml` (a manual override wins).
ensure_fast_linker() {
  local host ld
  host="$(rustc -vV 2>/dev/null | sed -n 's/^host: //p')"
  case "$host" in
    *-linux-gnu) ;;                # only the Linux host toolchain
    *) return 0 ;;                 # macOS/Windows/cross: leave the default linker
  esac
  if [ -f .cargo/config.toml ]; then
    echo "fast-linker: .cargo/config.toml already present — leaving it untouched"
    return 0
  fi
  if command -v mold >/dev/null 2>&1; then
    ld=mold
  elif command -v ld.lld >/dev/null 2>&1 || command -v lld >/dev/null 2>&1; then
    ld=lld
  else
    echo "fast-linker: no mold/lld on PATH — using the default linker (install mold, then re-run)"
    return 0
  fi
  mkdir -p .cargo
  cat > .cargo/config.toml <<CONFIG
# Auto-generated by scripts/lib/fast-linker.sh — faster incremental links via ${ld}.
# Gitignored (never committed). Delete to revert to the default linker; edit
# freely, the setup scripts won't overwrite an existing file. See docs/BUILD.md.
[target.${host}]
rustflags = ["-C", "link-arg=-fuse-ld=${ld}"]
CONFIG
  echo "fast-linker: wired ${ld} for ${host} (.cargo/config.toml)"
}
